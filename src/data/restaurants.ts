function validateRestaurantUrl(value: string, sourceOnly = false) {
  const url = new URL(value);

  if (
    url.protocol !== "https:" ||
    (sourceOnly && !trustedRestaurantSourceHosts.has(url.hostname))
  ) {
    throw new Error(`Otillåten restaurangkälla: ${url.hostname}`);
  }
}

function isExplicitlyClosedRestaurant(restaurant: Restaurant) {
  const status = restaurant.hours
    ?.trim()
    .replace(/^['"]|['"]$/g, "")
    .toLocaleLowerCase("sv-SE");

  if (!status) return false;

  return (
    status === "closed" ||
    status === "stängt" ||
    status === "stängd" ||
    status.startsWith("temporarily closed") ||
    status.startsWith("permanently closed") ||
    status.startsWith("tillfälligt stäng") ||
    status.startsWith("permanent stäng")
  );
}

